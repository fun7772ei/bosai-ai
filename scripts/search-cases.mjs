export function grade(item, ids) {
 const relevant = new Set(item.relevant), absent = !relevant.size;
 return { top1: !absent && relevant.has(ids[0]), top3: !absent && ids.slice(0,3).some(id => relevant.has(id)), wrongTop1: !absent && ids.length > 0 && !relevant.has(ids[0]), falsePositive: absent && ids.length > 0, correctAbstention: absent && !ids.length, dangerous: item.dangerous.includes(ids[0]), relevantRetrieved: ids.filter(id => relevant.has(id)).length, relevantTotal: relevant.size };
}
